"""
Баффы уровня ОТРЯДА, которые не принадлежат ни одному персонажу.

Кладите их в Team(buffs=...) — они учитываются один раз.
"""

from __future__ import annotations

from ..core.buffs import TEAM, Buff
from ..core.stats import S
from .tags import OFF

# --------------------------------------------------------------------------- #
#  Бонус лунных реакций от персонажа НЕ из лунного региона (не Moonsign)       #
# --------------------------------------------------------------------------- #
#  При E или Q такой персонаж на 20 с даёт отряду бонус урона лунных реакций
#  по своим статам (время действия не учитываем — постоянно):
#      пиро / электро / крио — 0.9% за каждые 100 АТК
#      гидро                 — 0.6% за каждые 1000 HP
#      гео                   — 1% за каждые 100 ЗЩ
#      анемо / дендро        — 2.25% за каждые 100 МС
#  Максимум 36%. Считаются статы ОДНОГО персонажа, эффекты не суммируются —
#  поэтому добавляйте один такой бафф на отряд.
#  В отрядах только из Moonsign-персонажей (как Цзы Бай / Линея / Колумбина /
#  Иллуги) его нет.

#: (стат, бонус за 1 единицу стата)
LUNAR_OUTSIDER_SCALING = {
    "pyro": ("atk", 0.009 / 100),
    "electro": ("atk", 0.009 / 100),
    "cryo": ("atk", 0.009 / 100),
    "hydro": ("hp", 0.006 / 1000),
    "geo": ("def", 0.01 / 100),
    "anemo": ("em", 0.0225 / 100),
    "dendro": ("em", 0.0225 / 100),
}
LUNAR_OUTSIDER_CAP = 0.36


def lunar_outsider_buff(character: str, element: str) -> Buff:
    """Бонус урона ВСЕХ лунных реакций отряду от статов `character` (вне поля)."""
    stat, per_unit = LUNAR_OUTSIDER_SCALING[element]
    return Buff(
        S.LUNAR_BONUS,
        lambda ctx: min(LUNAR_OUTSIDER_CAP,
                        per_unit * ctx.stat(character, stat, frozenset({OFF}))),
        target=TEAM,
        source=f"{character} (не из лунного региона): бонус лунных реакций от "
               f"{ {'atk': 'АТК', 'hp': 'HP', 'def': 'ЗЩ', 'em': 'МС'}[stat] } (макс. 36%)",
    )
