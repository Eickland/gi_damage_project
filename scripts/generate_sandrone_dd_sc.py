def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="только проверить, не писать")
    args = ap.parse_args()

    print(f"Новых составов: {len(TEAMS)}")
    if args.check:
        for s in TEAMS:
            print(" ", slug(s), "+", ", ".join(s))
        return 0

    root = Path(TEAMS_PATH[0])
    written = 0
    for supports in TEAMS:
        folder = root / slug(supports)
        builds_path = folder / "builds.py"
        if folder.exists() and builds_path.exists() and MARKER not in builds_path.read_text(encoding="utf-8"):
            print(f"ОШИБКА: {folder} существует и не помечен как сгенерированный")
            return 1
        folder.mkdir(parents=True, exist_ok=True)
        (folder / "__init__.py").write_text(
            f'"""Сандроне (ДД, SC) / {supports[0]} / {supports[1]} / {supports[2]}."""\n',
            encoding="utf-8",
        )
        builds_path.write_text(builds_source(supports), encoding="utf-8")
        (folder / "rosters.py").write_text(rosters_source(supports), encoding="utf-8")
        written += 1
        print(f"  {folder.name}")
    print(f"Создано отрядов: {written}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
