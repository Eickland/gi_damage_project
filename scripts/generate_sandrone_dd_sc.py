#!/usr/bin/env python3
"""Сгенерировать новые отряды «Сандроне — звёздный проводник».

    python -m scripts.generate_sandrone_dd_sc
    python -m scripts.generate_sandrone_dd_sc --check   # только проверить, не писать

Составы подбираются автоматически из пула саппортов:
  * 4 крио: Одетта, Ци Ци, Диона, Анастасия;
  * 3 электро: Алеша, Митя, Даника;
  * Водяница и Сахароза.
Нужны минимум один крио-саппорт (кроме Сандроне) и один электро.
Существующие отряды с Сандроне исключаются по набору саппортов.

Каждый отряд — тонкая папка, которая берёт ``builds.py`` из фабрики
``gi_damage/teams/_sandrone_dd_sc_factory.py``.
"""

from __future__ import annotations

import argparse
import importlib
import itertools
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from gi_damage.teams import __path__ as TEAMS_PATH
from gi_damage.teams._sandrone_dd_sc_factory import (
    SUPPORT_ORDER,
    SUPPORT_SLUG,
    SUPPORT_SPECS,
)

CRYO = ("Одетта", "Ци Ци", "Диона", "Анастасия")
ELECTRO = ("Алеша", "Митя", "Даника")
POOL = CRYO + ELECTRO + ("Водяница", "Сахароза")

MARKER = "AUTO-GENERATED by scripts/generate_sandrone_dd_sc.py"


def slug(supports: tuple[str, str, str]) -> str:
    return "sandrone_dd_" + "_".join(SUPPORT_SLUG[s] for s in supports)


def existing_support_sets() -> set[frozenset[str]]:
    out: set[frozenset[str]] = set()
    # Часть старых папок Сандроне лежит без __init__.py, поэтому pkgutil
    # их не видит — сканируем каталоги напрямую.
    for folder in sorted(Path(TEAMS_PATH[0]).glob("sandrone_*")):
        if not folder.is_dir() or folder.name.startswith("sandrone_dd_"):
            continue
        try:
            builds = importlib.import_module(f"gi_damage.teams.{folder.name}.builds")
        except Exception:
            continue
        for team in builds.all_teams().values():
            if team.dd_name() != "Сандроне":
                continue
            out.add(frozenset(
                b.name for b in team.builds if b.name != "Сандроне"
                and b.name in SUPPORT_SPECS
            ))
    return out


def planned_teams() -> tuple[tuple[str, str, str], ...]:
    existing = existing_support_sets()
    out = []
    for combo in itertools.combinations(POOL, 3):
        s = set(combo)
        if not (s & set(CRYO) and s & set(ELECTRO)):
            continue
        if frozenset(combo) in existing:
            continue
        out.append(combo)
    order = {name: i for i, name in enumerate(SUPPORT_ORDER)}
    out.sort(key=lambda t: tuple(order[x] for x in t))
    return tuple(out)


TEAMS = planned_teams()


def builds_source(supports: tuple[str, str, str]) -> str:
    names = ", ".join(repr(s) for s in supports)
    return f'''"""Сандроне (ДД, SC) / {supports[0]} / {supports[1]} / {supports[2]}.

{MARKER}.

Не редактировать вручную: логика отряда — в
``gi_damage/teams/_sandrone_dd_sc_factory.py``.
"""

from __future__ import annotations

from .._sandrone_dd_sc_factory import make_module

globals().update(make_module(({names})))
'''


