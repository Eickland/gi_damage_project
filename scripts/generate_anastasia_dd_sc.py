def existing_teams(skip: set[str]) -> set[tuple[str, frozenset[str]]]:
    """(ДД, набор персонажей) для всех уже существующих отрядов."""
    out: set[tuple[str, frozenset[str]]] = set()
    for m in pkgutil.iter_modules(TEAMS_PATH):
        if m.name.startswith("_") or m.name in skip:
            continue
        try:
            builds = importlib.import_module(f"gi_damage.teams.{m.name}.builds")
        except Exception as exc:
            print(f"! пропущен {m.name}: {type(exc).__name__}: {exc}")
            continue
        for team in builds.all_teams().values():
            out.add((team.dd_name(), frozenset(b.name for b in team.builds)))
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="только проверить, файлы не писать")
    args = ap.parse_args()

    slugs = {slug(s) for s in TEAMS}
    existing = existing_teams(slugs)
    existing_sets = {chars for _, chars in existing}
    duplicates = []
    for s in TEAMS:
        if frozenset(("Анастасия",) + s) in existing_sets:
            duplicates.append(s)
    if duplicates:
        print("ОШИБКА: такие отряды уже есть:")
        for s in duplicates:
            print("  ", slug(s), " + ".join(("Анастасия",) + s))
        return 1
    print(f"Проверка: {len(TEAMS)} составов, дублей с существующими отрядами нет.")

    if args.check:
        return 0

    root = Path(TEAMS_PATH[0])
    written = 0
    for supports in TEAMS:
        folder = root / slug(supports)
        builds_path = folder / "builds.py"
        if folder.exists() and builds_path.exists() and MARKER not in builds_path.read_text(encoding="utf-8"):
            print(f"ОШИБКА: {folder} существует и не помечен как сгенерированный")
            return 1
        folder.mkdir(parents=True, exist_ok=True)
        (folder / "__init__.py").write_text(
            f'"""Анастасия (ДД, SC) / {supports[0]} / {supports[1]} / {supports[2]}."""\n',
            encoding="utf-8",
        )
        builds_path.write_text(builds_source(supports), encoding="utf-8")
        (folder / "rosters.py").write_text(rosters_source(supports), encoding="utf-8")
        written += 1
        print(f"  {folder.name}")
    print(f"Создано отрядов: {written}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
